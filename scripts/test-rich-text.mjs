import assert from 'node:assert/strict';
import vm from 'node:vm';
import {readFile} from 'node:fs/promises';
const scope={window:{},document:{addEventListener(){}},URL};
vm.runInNewContext(await readFile(new URL('../public/rich-text.js',import.meta.url),'utf8'),scope);
const {render,visibleStream}=scope.window.LearnFlowText;
let checks=0;const check=(name,fn)=>{fn();checks++;console.log('ok '+name);};
check('raw HTML is escaped',()=>assert.ok(render('<img src=x onerror=alert(1)>').includes('&lt;img')));
check('script tags cannot execute',()=>assert.ok(!render('<script>alert(1)</script>').includes('<script')));
check('javascript links are not anchors',()=>assert.ok(!render('[bad](javascript:alert(1))').includes('<a ')));
check('data URLs are not anchors',()=>assert.ok(!render('[bad](data:text/html,test)').includes('<a ')));
check('https links use isolated new tabs',()=>assert.match(render('[文档](https://example.com/?a=1&b=2)'),/rel="noopener noreferrer"/));
check('code remains literal',()=>assert.match(render('```js\nconst x = "<b>";\n```'),/const x = &quot;&lt;b&gt;&quot;;/));
check('markdown table renders semantic header',()=>assert.match(render('| 方法 | 作用 |\n| --- | --- |\n| 自测 | 发现遗漏 |'),/<th scope="col"[^>]*>方法<\/th>/));
check('headings and lists remain readable',()=>assert.match(render('## 先试试\n\n1. 关上书\n2. 回答问题'),/<ol start="1"><li>关上书<\/li>/));
check('structured metadata is hidden while streaming',()=>assert.equal(visibleStream('正文\n```learnflow-next\n{"blockReady":true}'), '正文\n'));
check('split metadata prefixes never flash',()=>{const marker='```learnflow-next';for(let n=1;n<=marker.length;n++)assert.ok(!visibleStream('正文\n'+marker.slice(0,n)).includes('learnflow'));});
check('ordinary fenced code is kept',()=>assert.equal(visibleStream('正文\n```python\nprint(1)'), '正文\n```python\nprint(1)'));
check('inline code is escaped once',()=>assert.equal(render('`<tag>`'),'<p><code>&lt;tag&gt;</code></p>'));
console.log(`${checks} rich text checks passed`);
